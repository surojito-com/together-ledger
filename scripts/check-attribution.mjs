// Fails a pull request, or a push to main, that carries AI-tool or vendor attribution or a closing
// keyword.
//
// The owner's rule (CLAUDE.md, "Branch naming and attribution"): commits and pull requests read
// as Together Ledger's own work. No co-author trailer naming a tool, no "generated with" footer,
// no session link. Wording in CLAUDE.md alone did not hold — an earlier version of that file asked
// for the trailer, and the GitHub tooling cloud sessions use appends its own footer to every PR
// body it writes, server-side, whatever the session wrote (#294). So this checks, it does not ask.
//
// What it reads:
//
//   pull_request   the PR's own commits, its title and its body
//   push           the pushed commits
//
// The check itself needs no secrets and no network: the event payload and the checkout are enough.
//
// The one exception is the footer the session tooling appends to a PR body. Nobody writes it, a
// session cannot keep it out, and an edit through the same tooling only puts it back. Failing on
// it would turn every session's PR red until someone edited the body by hand, so `--strip-pr-body`
// removes exactly those footer lines with the workflow's own token — an edit that does not pass
// through that tooling, and so sticks — and the check then reads the cleaned body. Anything else
// that names a tool, in the body or anywhere, still fails.
//
// It also fails on a closing keyword (CLAUDE.md, "Issues are the project journey"). GitHub closes
// an issue when a merged PR's title or body, or a commit reaching main, puts close, fix or resolve
// (in any of their forms, any casing) before a reference to it, and it reads no further back than
// the keyword: "does not close #260" closed #260, and "Fixes #256" closed #256. So a keyword before
// a reference fails whatever comes before it, a "not" included. "Relates to #N" and "part of #N"
// carry no keyword and pass.
//
// Honest limits: the squash commit is written at merge time, after this has run, so merge with an
// explicit message (the PR title as the subject, a clean body). The push check on main catches a
// slip afterwards; it cannot prevent one. Issue and PR comments are not history and are not read.

import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';

const TOOLS = [
  'claude', 'anthropic', 'codex', 'openai', 'chatgpt', 'gpt-[0-9]', 'copilot', 'cursor', 'gemini',
  'devin-ai', 'aider', 'windsurf', 'codeium', 'tabnine', 'amazon q',
];
const tool = `(?:${TOOLS.join('|')})`;

const RULES = [
  { reason: 'a Co-Authored-By trailer naming an AI tool or vendor', pattern: new RegExp(`^[ \\t]*co-authored-by:.*\\b${tool}`, 'im') },
  { reason: 'a "Generated with/by" line naming an AI tool or vendor', pattern: new RegExp(`generated\\s+(?:with|by)\\b.*\\b${tool}`, 'im') },
  { reason: 'a claude.ai/code session link', pattern: /claude\.ai\/code/i },
];

// The line of `text` that holds `index`.
function lineAt(text, index) {
  const start = text.lastIndexOf('\n', index) + 1;
  const end = text.indexOf('\n', index);
  return text.slice(start, end === -1 ? undefined : end).trim();
}

// Every rule that matches `text`, with the line it matched on.
export function findAttribution(text) {
  if (!text) return [];
  const found = [];
  for (const { reason, pattern } of RULES) {
    const match = pattern.exec(text);
    if (match) found.push({ reason, line: lineAt(text, match.index) });
  }
  return found;
}

// The keywords GitHub honours, then the references it closes: #12, GH-12, owner/repo#12, or the
// issue's own address. A colon after the keyword still counts.
const CLOSING_KEYWORD = /\b(?:close[sd]?|fix(?:e[sd])?|resolve[sd]?)\b:?\s*(?:[\w.-]+\/[\w.-]+#\d+|#\d+|gh-\d+|https?:\/\/github\.com\/[\w.-]+\/[\w.-]+\/issues\/\d+)\b/gi;

// Every closing keyword before an issue reference in `text`, with the line it is on.
export function findClosingKeywords(text) {
  if (!text) return [];
  return [...text.matchAll(CLOSING_KEYWORD)].map((match) => ({
    reason: `a closing keyword, "${match[0]}": a merge would close that issue. Write "Relates to #N" (or "part of #N") instead`,
    line: lineAt(text, match.index),
  }));
}

const FOOTER_LINE = /^\s*_?Generated (?:with|by) \[Claude Code\]\(https:\/\/claude\.(?:ai|com)\/[^)]*\)_?\s*$/i;
const SESSION_LINE = /^\s*<?https:\/\/claude\.ai\/code\/session_[A-Za-z0-9]+>?\s*$/i;

// Removes the footer the session tooling appends: its "Generated by [Claude Code](…)" line, a bare
// session link on a line of its own, and the `---` rule and blank lines left above them. Every other
// character is kept as written; a footer worded any other way is left for the check to fail on.
export function stripToolFooter(body) {
  if (!body) return body;
  const lines = body.replace(/\r\n/g, '\n').split('\n');
  let removed = false;
  for (;;) {
    while (lines.length && lines.at(-1).trim() === '') lines.pop();
    const last = lines.at(-1);
    if (last !== undefined && (FOOTER_LINE.test(last) || SESSION_LINE.test(last))) {
      lines.pop();
      removed = true;
      continue;
    }
    if (removed && last !== undefined && last.trim() === '---') {
      lines.pop();
      continue;
    }
    break;
  }
  return removed ? lines.join('\n').trimEnd() : body;
}

function git(...args) {
  return execFileSync('git', args, { encoding: 'utf8' });
}

// Full messages of the commits in `range`, as [{ sha, message }].
function commitMessages(...range) {
  return git('log', '--format=%H%x00%B%x1e', ...range)
    .split('\x1e')
    .map((entry) => entry.trim())
    .filter(Boolean)
    .map((entry) => {
      const [sha, message = ''] = entry.split('\x00');
      return { sha, message };
    });
}

function hasRef(ref) {
  try {
    git('rev-parse', '--verify', '--quiet', `${ref}^{commit}`);
    return true;
  } catch {
    return false;
  }
}

// What to read for this event, as [{ where, text }].
export function subjects(eventName, event, readCommits = commitMessages, refExists = hasRef) {
  const items = [];
  if (eventName === 'pull_request' || eventName === 'pull_request_target') {
    const pr = event.pull_request;
    items.push({ where: 'PR title', text: pr.title });
    items.push({ where: 'PR body', text: stripToolFooter(pr.body ?? '') });
    const base = refExists(`origin/${pr.base.ref}`) ? `origin/${pr.base.ref}` : pr.base.sha;
    for (const { sha, message } of readCommits(pr.head.sha, `^${base}`)) {
      items.push({ where: `commit ${sha.slice(0, 7)}`, text: message });
    }
  } else if (eventName === 'push') {
    const zero = /^0+$/.test(event.before ?? '');
    const range = zero || !refExists(event.before) ? [event.after, '-1'] : [`${event.before}..${event.after}`];
    for (const { sha, message } of readCommits(...range)) {
      items.push({ where: `commit ${sha.slice(0, 7)}`, text: message });
    }
  }
  return items;
}

export function check(items) {
  return items.flatMap(({ where, text }) => [
    ...findAttribution(text).map((finding) => ({ where, kind: 'attribution', ...finding })),
    ...findClosingKeywords(text).map((finding) => ({ where, kind: 'closing', ...finding })),
  ]);
}

async function stripPrBody(event) {
  const pr = event.pull_request;
  if (!pr) return;
  const cleaned = stripToolFooter(pr.body ?? '');
  if (cleaned === (pr.body ?? '')) {
    console.log('The PR body carries no tool footer.');
    return;
  }
  const token = process.env.GITHUB_TOKEN;
  if (!token) throw new Error('GITHUB_TOKEN is needed to remove the tool footer from the PR body.');
  const response = await fetch(pr.url, {
    method: 'PATCH',
    headers: {
      accept: 'application/vnd.github+json',
      authorization: `Bearer ${token}`,
      'content-type': 'application/json',
    },
    body: JSON.stringify({ body: cleaned }),
  });
  if (!response.ok) throw new Error(`Removing the tool footer from the PR body failed: HTTP ${response.status}`);
  console.log('Removed the tool footer from the PR body.');
}

async function main() {
  const eventName = process.env.GITHUB_EVENT_NAME;
  const event = JSON.parse(readFileSync(process.env.GITHUB_EVENT_PATH, 'utf8'));
  if (process.argv.includes('--strip-pr-body')) {
    await stripPrBody(event);
    return;
  }
  const findings = check(subjects(eventName, event));
  if (findings.length === 0) {
    console.log('No AI-tool or vendor attribution and no closing keyword found.');
    return;
  }
  for (const { where, reason, line } of findings) {
    console.error(`${where}: ${reason}\n    ${line}`);
  }
  if (findings.some(({ kind }) => kind === 'attribution')) {
    console.error('\nCommits and pull requests read as Together Ledger\'s own work — see CLAUDE.md, "Branch naming and attribution".');
  }
  if (findings.some(({ kind }) => kind === 'closing')) {
    console.error('\nA merge must never close an issue: write "Relates to #N" instead, and the owner closes it — see CLAUDE.md, "Issues are the project journey". "Not" or "does not" before the keyword does not stop GitHub.');
  }
  process.exitCode = 1;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
